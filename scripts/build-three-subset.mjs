// Maintenance only: npm ci && node scripts/build-three-subset.mjs [--check].
// Generated artifact is committed; serving and deploying require no build.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {build} from 'esbuild';
const scenes=['assets/js/scene.js','assets/js/process-scene.js'];
const exports=[...new Set(scenes.flatMap(path=>[...readFileSync(path,'utf8').matchAll(/THREE\.(\w+)/g)].map(m=>m[1])))].sort();
const result=await build({stdin:{contents:`export {${exports.join(',')}} from 'three';`,resolveDir:process.cwd()},bundle:true,minify:true,format:'esm',target:'es2020',write:false,legalComments:'inline',banner:{js:'// Three.js 0.180.0 site subset; generated by scripts/build-three-subset.mjs; MIT license: ../LICENSE.three.txt'}});
const bytes=result.outputFiles[0].contents;
const sha256=createHash('sha256').update(bytes).digest('hex');
const path=`assets/vendor/three-0.180.0/three.site.${sha256.slice(0,12)}.min.js`;
const manifest=JSON.parse(readFileSync('dependencies.json','utf8'));
if(process.argv.includes('--check')){
 if(manifest.runtime?.path!==path||!Buffer.from(bytes).equals(readFileSync(path)))throw Error('Stale Three.js subset; run node scripts/build-three-subset.mjs');
}else{
 writeFileSync(path,bytes);
 manifest.runtime={path,sha256,exports,generator:'esbuild 0.25.11; npm ci && node scripts/build-three-subset.mjs'};
 writeFileSync('dependencies.json',JSON.stringify(manifest,null,2)+'\n');
 for(const source of [...scenes,'assets/js/main.js']){
  const old=readFileSync(source,'utf8');
  const next=old.replace(/three\.(?:module|site\.[a-f0-9]+)\.min\.js/g,path.split('/').at(-1));
  writeFileSync(source,next);
 }
}
console.log(path,bytes.length,'bytes;',exports.length,'exports');
